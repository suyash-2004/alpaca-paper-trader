"""Broker / market-data interfaces used by the runner. The only real implementation is the
paper-only Alpaca adapter in alpaca_adapter.py; tests use in-memory fakes.

Normalised shapes (plain dicts, money as strings/Decimal-convertible):
  account   : account_number,status,currency,cash,equity,last_equity,multiplier,shorting_enabled,
              options_trading_level,trading_blocked,account_blocked,accrued_fees,pending_transfer_out
  config    : no_shorting,max_margin_multiplier,max_options_trading_level,suspend_trade
  clock     : is_open,timestamp,next_open,next_close
  position  : symbol,qty,avg_entry_price,cost_basis,market_value
  order     : id,client_order_id,symbol,side,status,type,qty,filled_qty,filled_avg_price,
              limit_price,stop_price,created_at,filled_at,legs[]
  asset     : symbol,asset_class,status,tradable,exchange
"""
from typing import Dict, List, Optional, Protocol

from .strategy import Bar


class Broker(Protocol):
    def get_account(self) -> dict: ...
    def get_configurations(self) -> dict: ...
    def set_configurations(self, **changes) -> dict: ...
    def get_clock(self) -> dict: ...
    def get_trading_days(self, start, end) -> list: ...
    def get_positions(self) -> List[dict]: ...
    def get_orders(self, status: str, after=None, limit: int = 500) -> List[dict]: ...
    def get_asset(self, symbol: str) -> dict: ...
    def submit_bracket_buy(self, symbol: str, qty: int, limit_price: float, take_profit: float,
                           stop_loss: float, client_order_id: str) -> dict: ...
    def submit_limit_buy(self, symbol: str, qty: int, limit_price: float, client_order_id: str) -> dict: ...
    def submit_market_sell(self, symbol: str, qty: int, client_order_id: str) -> dict: ...
    def cancel_order(self, order_id: str) -> None: ...


class MarketData(Protocol):
    def get_bars(self, symbols: List[str], start, end) -> Dict[str, List[Bar]]: ...
    def get_latest_quotes(self, symbols: List[str]) -> Dict[str, dict]: ...  # {bid, ask, ts}
